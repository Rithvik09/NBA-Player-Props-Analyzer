"""Smoke tests for scripts/backup_db.sh.

Skipped when pg_dump/gzip aren't on the host (e.g. minimal CI sandboxes).
The behaviour we care about: a backup of a live DB is (a) created,
(b) carries pg_dump's completion marker, and (c) round-trips back into a
usable database.
"""
from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path

import psycopg
import pytest

SCRIPT = Path(__file__).resolve().parent.parent / "scripts" / "backup_db.sh"


def _have(*tools: str) -> bool:
    return all(shutil.which(t) for t in tools)


pytestmark = pytest.mark.skipif(
    not _have("pg_dump", "psql", "gzip", "gunzip", "bash"),
    reason="needs pg_dump/psql/gzip/bash on PATH",
)


@pytest.fixture
def seeded_db(pg_dsn):
    """A table with known rows, dropped again on teardown.

    This one deliberately does NOT use the rollback fixture: pg_dump
    connects as a separate client and can only see committed data.
    """
    conn = psycopg.connect(pg_dsn, autocommit=True)
    conn.execute("DROP TABLE IF EXISTS backup_smoke_bets")
    conn.execute(
        "CREATE TABLE backup_smoke_bets ("
        "  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
        "  stake DOUBLE PRECISION)"
    )
    conn.execute(
        "INSERT INTO backup_smoke_bets (stake) VALUES (%s), (%s), (%s)",
        (1.0, 2.0, 3.0),
    )
    yield pg_dsn
    conn.execute("DROP TABLE IF EXISTS backup_smoke_bets")
    conn.close()


def test_backup_creates_compressed_file(seeded_db, tmp_path):
    env = os.environ.copy()
    env["BACKUP_DIR"] = str(tmp_path / "out")
    r = subprocess.run(
        ["bash", str(SCRIPT), seeded_db],
        env=env, capture_output=True, text=True, timeout=60,
    )
    assert r.returncode == 0, r.stderr
    files = list((tmp_path / "out").glob("*.sql.gz"))
    assert len(files) == 1
    assert files[0].stat().st_size > 0


def test_backup_round_trips_data(seeded_db, tmp_path):
    env = os.environ.copy()
    env["BACKUP_DIR"] = str(tmp_path / "out")
    subprocess.run(
        ["bash", str(SCRIPT), seeded_db],
        env=env, check=True, timeout=60, capture_output=True,
    )
    backup_gz = next((tmp_path / "out").glob("*.sql.gz"))
    subprocess.run(["gunzip", "-k", str(backup_gz)], check=True)
    dump = backup_gz.with_suffix("").read_text()
    # The dump must carry both the data and pg_dump's completion marker.
    assert "backup_smoke_bets" in dump
    assert "PostgreSQL database dump complete" in dump
    for stake in ("1", "2", "3"):
        assert stake in dump


def test_backup_missing_dsn_errors(tmp_path):
    env = os.environ.copy()
    env["BACKUP_DIR"] = str(tmp_path)
    env.pop("DATABASE_URL", None)
    r = subprocess.run(
        ["bash", str(SCRIPT)],
        env=env, capture_output=True, text=True, timeout=10,
    )
    assert r.returncode != 0
    assert "no connection string" in r.stderr


def test_backup_unreachable_db_errors(tmp_path):
    env = os.environ.copy()
    env["BACKUP_DIR"] = str(tmp_path)
    r = subprocess.run(
        ["bash", str(SCRIPT), "postgresql:///definitely_not_a_database_here"],
        env=env, capture_output=True, text=True, timeout=30,
    )
    assert r.returncode != 0
    assert not list(Path(tmp_path).glob("*.sql*"))


def test_backup_keep_flag_validates_integer(seeded_db, tmp_path):
    env = os.environ.copy()
    env["BACKUP_DIR"] = str(tmp_path / "out")
    r = subprocess.run(
        ["bash", str(SCRIPT), seeded_db, "--keep", "not-a-number"],
        env=env, capture_output=True, text=True, timeout=60,
    )
    assert r.returncode != 0
    assert "non-negative integer" in r.stderr
