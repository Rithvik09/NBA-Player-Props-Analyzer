"""Public/sharp betting splits from Action Network's scoreboard feed.

For every game on the board the feed reports, per book and per market,
what share of *tickets* and what share of *money* sits on each side.
The gap between those two numbers is the signal: 11% of tickets and 43%
of the money on an underdog is a different market than 11% and 11%.

Deliberately not part of :mod:`src.odds_tracker`. That module talks to
The Odds API — paid, quota-limited, keyed — and every design decision in
it (opt-in capture, a credit floor, two snapshots a game day) exists to
ration credits. This source is free and needs no key, so it is polled on
a plain timer and gated on nothing.

What it is, honestly: an undocumented internal endpoint behind
actionnetwork.com's scoreboard. No contract, no changelog. It can change
shape or start demanding auth any day, and the way we would find out is
that the table stopped filling — which looks exactly like a night with
no NBA. Hence :meth:`BettingSplitsTracker.capture` shouting at ERROR
whenever a parse yields nothing; see the canary section below.

Book identity is the integer ``book_id`` the feed sends and nothing
else. The payload carries no name for it and ``/web/v1/books`` answers
400, so any ``15 -> "DraftKings"`` mapping here would be invention, not
data. Resolve it later by cross-referencing prices against a book we can
name, and record how.
"""

import logging
import os
from datetime import datetime, timezone

import psycopg
import requests

from src import db

log = logging.getLogger(__name__)

PUBLIC_BETTING_URL = \
    "https://api.actionnetwork.com/web/v2/scoreboard/publicbetting/nba"

# Game-level markets we keep. The feed also carries
# ``core_bet_type_6_team_score`` (team totals) with splits of its own;
# it is out of scope until something models team totals, and storing it
# under a market name no reader knows would be worse than dropping it.
MARKETS = ("moneyline", "spread", "total")

# Twenty minutes. The source is free, so cadence is a courtesy question
# rather than a budget one: often enough to watch money move across an
# evening, slow enough that ~70 requests a day is nothing to them.
DEFAULT_POLL_INTERVAL_SECONDS = 1200

# Say who we are. A browser string would be a lie, and the point of a
# User-Agent on an endpoint nobody published is that they can tell what
# we are and ask us to stop.
DEFAULT_USER_AGENT = (
    "NBA-Player-Props-Analyzer/1.0 "
    "(personal NBA model research; https://github.com/Rithvik09)"
)

HTTP_TIMEOUT_SECONDS = 30


def poll_interval_seconds() -> int:
    """Seconds between polls, from ``BETTING_SPLITS_POLL_INTERVAL``."""
    try:
        return int(os.environ.get("BETTING_SPLITS_POLL_INTERVAL",
                                  str(DEFAULT_POLL_INTERVAL_SECONDS)))
    except ValueError:
        return DEFAULT_POLL_INTERVAL_SECONDS


def user_agent() -> str:
    """Identity sent with every request, from ``BETTING_SPLITS_USER_AGENT``."""
    return os.environ.get("BETTING_SPLITS_USER_AGENT", "").strip() \
        or DEFAULT_USER_AGENT


class BettingSplitsTracker:
    """Fetch, parse and persist Action Network public betting splits."""

    def __init__(self, db_path: str | None = None):
        self.db_path = db_path
        self._init_db()

    # ---- DB setup ---------------------------------------------------------

    def _init_db(self):
        """Create ``betting_splits_history`` if it doesn't exist.

        Same conventions as ``game_line_history`` in odds_tracker: an
        identity PK, TEXT ``snapshot_time``, and a UNIQUE tuple over one
        observation so re-polling the same minute is a no-op.

        What identifies one observation is
        ``(event_id, book_id, market, side, is_live, snapshot_time)``.
        ``team_id`` is not in it — ``side`` already separates the two
        outcomes of every market, and totals carry no team at all, so a
        NULL in the tuple would (on PostgreSQL 14, with no ``NULLS NOT
        DISTINCT``) let duplicates through. ``is_live`` *is* in it
        because an in-progress game repeats its whole board with live
        prices; without it one of the two silently loses the race.

        The Action Network ``event_id`` is its own identifier — not the
        NBA ``game_id``, not the Odds API event id ``game_line_history``
        keys on. The matchup and UTC start date travel with every row so
        a later join has a natural key to work from.
        """
        conn = db.connect(self.db_path)
        c = conn.cursor()
        c.execute("""
            CREATE TABLE IF NOT EXISTS betting_splits_history (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                event_id BIGINT NOT NULL,
                book_id INTEGER NOT NULL,
                market TEXT NOT NULL,
                side TEXT NOT NULL,
                team_id BIGINT,
                line DOUBLE PRECISION,
                odds DOUBLE PRECISION,
                tickets_pct DOUBLE PRECISION,
                money_pct DOUBLE PRECISION,
                is_live BOOLEAN NOT NULL DEFAULT FALSE,
                home_team_abbr TEXT,
                away_team_abbr TEXT,
                start_time TEXT,
                start_date_utc TEXT,
                snapshot_time TEXT NOT NULL,
                UNIQUE(event_id, book_id, market, side, is_live, snapshot_time)
            )
        """)
        conn.commit()
        conn.close()
        log.info("[splits] DB tables initialized")

    # ---- API call ---------------------------------------------------------

    def fetch(self) -> dict | None:
        """GET the public-betting scoreboard, or ``None`` on failure.

        No key, no params — the endpoint takes none. Errors return
        ``None`` rather than raising so the poll loop survives them, but
        they are logged at ERROR: on an endpoint that could start
        requiring auth tomorrow, a 403 is news.
        """
        try:
            resp = requests.get(
                PUBLIC_BETTING_URL,
                headers={"User-Agent": user_agent(),
                         "Accept": "application/json"},
                timeout=HTTP_TIMEOUT_SECONDS,
            )
            resp.raise_for_status()
            return resp.json()
        except requests.exceptions.HTTPError as e:
            log.error(
                "[splits] Action Network returned HTTP %s — this endpoint is "
                "undocumented and may have changed or started requiring auth: %s",
                getattr(e.response, "status_code", "?"), e,
            )
            return None
        except requests.exceptions.RequestException as e:
            log.error("[splits] request to Action Network failed: %s", e)
            return None
        except ValueError as e:  # non-JSON body behind a 200
            log.error("[splits] Action Network response was not JSON: %s", e)
            return None

    # ---- Parsing ----------------------------------------------------------

    def parse(self, payload: dict, snapshot_time: str) -> list[tuple]:
        """Rows for every outcome in ``payload`` that carries ``bet_info``.

        Outcomes without ``bet_info`` are skipped, not an error: one of
        the six books on a typical slate (book 30, measured 2026-10-21)
        quotes prices and reports no splits whatsoever. This table means
        "an observed split", so a row with no percentages in it would be
        noise.

        A malformed game or outcome is skipped rather than raised on,
        for the same reason ``_store_game_lines`` does it: one bad game
        must not cost us the ten good ones.
        """
        rows: list[tuple] = []
        for game in payload.get("games") or []:
            event_id = game.get("id")
            if event_id is None:
                continue
            home_abbr, away_abbr = self._matchup(game)
            start_time = game.get("start_time") or None
            for book_id, book in (game.get("markets") or {}).items():
                event_markets = (book or {}).get("event") or {}
                for market, outcomes in event_markets.items():
                    if market not in MARKETS:
                        continue
                    for outcome in outcomes or []:
                        row = self._row(
                            outcome, market, event_id, book_id,
                            home_abbr, away_abbr, start_time, snapshot_time,
                        )
                        if row is not None:
                            rows.append(row)
        return rows

    @staticmethod
    def _matchup(game: dict) -> tuple[str | None, str | None]:
        """``(home_abbr, away_abbr)`` for one game.

        The ``teams`` array is not ordered home-first — 295286 listed
        the home team first and 295287 did not on the same slate — so
        the sides come from the explicit ``home_team_id`` /
        ``away_team_id`` rather than from position.
        """
        by_id = {t.get("id"): t.get("abbr") for t in game.get("teams") or []}
        return by_id.get(game.get("home_team_id")), \
            by_id.get(game.get("away_team_id"))

    @staticmethod
    def _row(outcome: dict, market: str, event_id, book_id,
             home_abbr, away_abbr, start_time: str | None,
             snapshot_time: str) -> tuple | None:
        bet_info = outcome.get("bet_info")
        side = outcome.get("side")
        if not bet_info or not side:
            return None
        # The ``value`` inside tickets/money is always 0 in this feed —
        # only ``percent`` is populated, so only ``percent`` is stored.
        tickets = (bet_info.get("tickets") or {}).get("percent")
        money = (bet_info.get("money") or {}).get("percent")
        value = outcome.get("value")
        # A moneyline's ``value`` is 0: no line, rather than a line of
        # zero. game_line_history NULLs the same case on h2h.
        line = None if market == "moneyline" else value
        # Totals carry no team, and book 30 sends team_id 0 for them.
        team_id = outcome.get("team_id") or None
        try:
            return (
                int(event_id), int(book_id), market, side,
                None if team_id is None else int(team_id),
                None if line is None else float(line),
                None if outcome.get("odds") is None else float(outcome["odds"]),
                None if tickets is None else float(tickets),
                None if money is None else float(money),
                bool(outcome.get("is_live")),
                home_abbr, away_abbr, start_time,
                start_time[:10] if start_time else None,
                snapshot_time,
            )
        except (TypeError, ValueError):
            log.warning(
                "[splits] skipping unparseable %s outcome on event %s book %s",
                market, event_id, book_id,
            )
            return None

    # ---- Persistence ------------------------------------------------------

    def store(self, rows: list[tuple]) -> int:
        """Insert ``rows``; returns how many were new.

        Re-polling inside the same ``snapshot_time`` conflicts on the
        UNIQUE tuple and inserts nothing, so a second capture in the
        same second legitimately returns 0.
        """
        if not rows:
            return 0
        conn = db.connect(self.db_path)
        c = conn.cursor()
        stored = 0
        try:
            for row in rows:
                # Per-row savepoint, same reasoning as the odds tables:
                # one bad row must not poison the transaction and
                # discard the rest of the snapshot.
                c.execute("SAVEPOINT splits_row")
                try:
                    c.execute("""
                        INSERT INTO betting_splits_history
                        (event_id, book_id, market, side, team_id, line, odds,
                         tickets_pct, money_pct, is_live, home_team_abbr,
                         away_team_abbr, start_time, start_date_utc,
                         snapshot_time)
                        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s,
                                %s, %s, %s, %s)
                        ON CONFLICT DO NOTHING
                    """, row)
                    # Read before the RELEASE below: rowcount tracks the
                    # last statement executed on the cursor, so reading
                    # it afterwards reports on the savepoint, not the
                    # insert.
                    inserted = c.rowcount
                except psycopg.Error as e:
                    c.execute("ROLLBACK TO SAVEPOINT splits_row")
                    log.warning("[splits] insert error: %s", e)
                else:
                    c.execute("RELEASE SAVEPOINT splits_row")
                    stored += inserted
            conn.commit()
        finally:
            conn.close()
        return stored

    # ---- One poll ---------------------------------------------------------

    def capture(self) -> int:
        """Fetch, parse and store one snapshot. Returns rows written.

        The canary lives here. This endpoint is undocumented, so the
        realistic failure is not an exception — it is a 200 whose shape
        we no longer understand, leaving an empty table that is
        indistinguishable from a night with no NBA. Every way of
        arriving at zero rows therefore logs at ERROR, naming what was
        expected against what was found. That does mean a genuine
        off-day (the All-Star break, the back of the calendar) logs an
        error too; a false alarm twice a season is the cheaper mistake.
        """
        payload = self.fetch()
        if payload is None:
            log.error(
                "[splits] no snapshot taken: expected a JSON board from %s, "
                "the request failed. Nothing was stored.", PUBLIC_BETTING_URL,
            )
            return 0

        snapshot_time = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
        games = payload.get("games") or []
        rows = self.parse(payload, snapshot_time)

        if not games:
            log.error(
                "[splits] expected a slate of NBA games from %s, found 0 games. "
                "Either there is genuinely no NBA today or the endpoint has "
                "changed shape — an empty table looks the same either way.",
                PUBLIC_BETTING_URL,
            )
            return 0
        if not rows:
            log.error(
                "[splits] expected public betting splits, found %d games and 0 "
                "outcomes carrying bet_info across markets %s. The board is "
                "there and the splits are not, which is what it would look "
                "like if this endpoint stopped publishing them.",
                len(games), ", ".join(MARKETS),
            )
            return 0

        stored = self.store(rows)
        log.info(
            "[splits] stored %d split rows across %d games (%s)",
            stored, len(games), snapshot_time,
        )
        return stored
